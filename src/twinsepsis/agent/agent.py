@dataclass
class _ToolRun:
    index: int
    tool: str
    ok: bool
    arguments: dict[str, Any] | None = None
    result: Any = None
    error_type: str | None = None
    error_message: str | None = None
    duration_ms: float = 0.0
    # "llm", "fallback" or "tools_only".  Recorded so traces and responses make
    # clear whether the model chose the call or a deterministic check did.
    origin: str = "llm"


def _validate_schema(instance: Any, schema: Mapping[str, Any], label: str) -> None:
    validator = jsonschema.Draft202012Validator(schema)
    error = best_match(validator.iter_errors(instance))
    if error is None:
        return
    path = "/".join(str(part) for part in error.absolute_path) or "<root>"
    raise _ToolFailure("invalid_arguments", f"{label} at {path}: {error.message}")


def _parse_arguments(raw: str) -> dict[str, Any]:
    if raw is None or raw.strip() == "":
        return {}
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise _ToolFailure(
            "invalid_arguments",
            f"arguments are not valid JSON: {exc.msg} (line {exc.lineno})",
        ) from exc
    if not isinstance(parsed, dict):
        raise _ToolFailure("invalid_arguments", "arguments must be a JSON object")
    return parsed


def _json_safe(value: Any) -> Any:
    try:
        return json.loads(json.dumps(value, allow_nan=False))
    except (TypeError, ValueError) as exc:
        raise _ToolFailure(
            "tool_error", f"tool produced a value that is not JSON-safe: {exc}"
        ) from exc


def _last_ok(results: Sequence[_ToolRun], tool: str) -> Any:
    for run in reversed(results):
        if run.tool == tool and run.ok:
            return run.result
    return None


