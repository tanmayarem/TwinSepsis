class SepsisAgent:
    """Tool-using agent bound to one patient twin and one scored hour."""

    def __init__(
        self,
        twin: PatientTwin,
        llm: ChatClient | None,
        *,
        max_tool_calls: int = MAX_TOOL_CALLS,
        trace: TraceLogger | None = None,
        trace_path: str | Path | None = None,
        trace_dir: str | Path | None = None,
        trace_enabled: bool = True,
    ) -> None:
        if not isinstance(twin, PatientTwin):
            raise TypeError("twin must be a PatientTwin")
        if isinstance(max_tool_calls, bool) or not isinstance(max_tool_calls, int):
            raise ValueError("max_tool_calls must be an integer")
        if not 1 <= max_tool_calls <= MAX_TOOL_CALLS:
            raise ValueError(
                f"max_tool_calls must be between 1 and {MAX_TOOL_CALLS}"
            )

        self.twin = twin
        self._llm = llm
        self.max_tool_calls = max_tool_calls
        self._trace = trace or TraceLogger(
            trace_path,
            trace_dir=trace_dir,
            enabled=trace_enabled,
        )

    # -- capabilities --------------------------------------------------

    @property
    def available_tools(self) -> list[str]:
        model = self.twin.model
        available = {"clinical_scores", "list_interventions"}

        if getattr(model, "supports_prediction", True):
            available.update(
                {"get_twin_state", "predict_risk", "risk_trajectory"}
            )
            if getattr(model, "supports_simulation", True):
                available.add("simulate_intervention")

        if getattr(model, "supports_prediction", True) and getattr(
            model, "supports_explanation", True
        ):
            available.add("explain_risk")

        return [name for name in TOOL_ORDER if name in available]

    # -- context validation -------------------------------------------

    def _validate_context(self, patient_id: str, hour: int) -> None:
        if not isinstance(patient_id, str) or not patient_id.strip():
            raise AgentContextError("patient_id must be a non-empty string")
        if patient_id != self.twin.patient_id:
            raise AgentContextError(
                "patient_id does not match the twin's patient; refusing to score "
                "a different patient"
            )
        if isinstance(hour, bool) or not isinstance(hour, int):
            raise AgentContextError("hour must be an integer")
        if hour < 1:
            raise AgentContextError("hour must be >= 1")
        if hour != self.twin.hours:
            raise AgentContextError(
                "hour must equal the number of hourly rows in the twin "
                f"({self.twin.hours}); construct the twin with history up to the "
                "requested hour"
            )

    # -- tool execution ------------------------------------------------

    def _execute_tool(
        self,
        name: str,
        raw_arguments: str,
        available: Sequence[str],
    ) -> tuple[dict[str, Any], Any]:
        if name not in TOOL_SPECS:
            raise _ToolFailure("unknown_tool", f"unknown tool {name!r}")

        arguments = _parse_arguments(raw_arguments)
        merged = dict(_DEFAULT_ARGUMENTS.get(name, {}))
        merged.update(arguments)
        _validate_schema(merged, TOOL_SPECS[name]["parameters"], "arguments")

        if name not in available:
            model = self.twin.model
            raise _ToolFailure(
                "tool_unavailable",
                f"{name!r} is not supported by risk model {model.name!r}",
            )

        try:
            if name == "get_twin_state":
                from .tools import get_twin_state

                result = get_twin_state(self.twin, **merged)
            elif name == "predict_risk":
                from .tools import predict_risk

                result = predict_risk(self.twin)
            elif name == "explain_risk":
                from .tools import explain_risk

                result = explain_risk(self.twin, **merged)
            elif name == "risk_trajectory":
                result = self._risk_trajectory(**merged)
            elif name == "clinical_scores":
                from .tools import clinical_scores

                result = clinical_scores(self.twin)
            elif name == "list_interventions":
                from .tools import list_interventions

                result = list_interventions()
            elif name == "simulate_intervention":
                from .tools import simulate_intervention

                result = simulate_intervention(self.twin, **merged)
            else:  # pragma: no cover - guarded by TOOL_SPECS
                raise _ToolFailure("unknown_tool", f"unknown tool {name!r}")
        except _ToolFailure:
            raise
        except Exception as exc:  # tool failures are reported, never hidden
            message = f"{type(exc).__name__}: {exc}"
            raise _ToolFailure("tool_error", message[:500]) from exc

        return merged, _json_safe(result)

    def _risk_trajectory(self, max_hours: int = 24) -> dict[str, Any]:
        if isinstance(max_hours, bool) or not isinstance(max_hours, int):
            raise ValueError("max_hours must be an integer")
        if not 1 <= max_hours <= 168:
            raise ValueError("max_hours must be between 1 and 168")

        total = self.twin.hours
        if total == 0:
            raise ValueError("twin has no history")

        start = max(1, total - max_hours + 1)
        history = self.twin.history
        points: list[dict[str, Any]] = []
        for end in range(start, total + 1):
            window = history.iloc[:end].copy()
            risk = float(self.twin.model.predict_proba(window))
            if not 0.0 <= risk <= 1.0:
                raise ValueError(f"model returned probability outside [0, 1]: {risk}")
            points.append({"hour": end, "risk": risk})

        return {
            "patient_id": self.twin.patient_id,
            "hours": total,
            "from_hour": start,
            "to_hour": total,
            "threshold": self.twin.model.threshold,
            "risk_model": model_identity(self.twin.model),
            "risks": points,
            "note": "Each point uses only data available at that hour.",
        }

    def risk_trajectory(self, max_hours: int = 24) -> dict[str, Any]:
        """Public access to the causal historical trajectory.

        The dashboard needs the same prefix-based scoring the ``risk_trajectory``
        tool returns, without going through the LLM or an ``AgentContext``.  It
        delegates here so there is exactly one implementation of the scoring
        loop and one source of model identity.
        """

        return self._risk_trajectory(max_hours=max_hours)

    # -- tracing -------------------------------------------------------

    def _trace_tool(self, run: _ToolRun, call: ToolCallRequest) -> None:
        self._trace.record(
            "tool_call",
            call_index=run.index,
            tool=run.tool,
            tool_call_id=call.id,
            arguments=run.arguments,
            ok=run.ok,
            error_type=run.error_type,
            duration_ms=run.duration_ms,
            origin=run.origin,
            risk_model=model_identity(self.twin.model),
            llm_provider=getattr(self._llm, "provider", None),
            llm_model=getattr(self._llm, "model", None),
        )

    def _run_tool_call(
        self,
        call: ToolCallRequest,
        index: int,
        available: Sequence[str],
        *,
        origin: str = "llm",
    ) -> _ToolRun:
        start = time.perf_counter()
        try:
            arguments, result = self._execute_tool(
                call.name, call.arguments, available
            )
            run = _ToolRun(
                index=index,
                tool=call.name,
                ok=True,
                arguments=arguments,
                result=result,
                origin=origin,
            )
        except _ToolFailure as exc:
            run = _ToolRun(
                index=index,
                tool=call.name,
                ok=False,
                arguments=None,
                error_type=exc.kind,
                error_message=exc.message,
                origin=origin,
            )
        except Exception as exc:  # defensive: never let a tool crash the run
            run = _ToolRun(
                index=index,
                tool=call.name,
                ok=False,
                arguments=None,
                error_type="internal_error",
                error_message=f"{type(exc).__name__}: {exc}"[:500],
                origin=origin,
            )

        run.duration_ms = round((time.perf_counter() - start) * 1000, 3)
        self._trace_tool(run, call)
        return run

    # -- completeness check -------------------------------------------

    def _ensure_prediction(
        self,
        results: list[_ToolRun],
        available: Sequence[str],
    ) -> bool:
        """Run ``predict_risk`` if the LLM left a supported prediction out.

        This is a deterministic completeness check, not a replacement for
        LLM-selected tool calls: it runs only after the LLM loop has finished,
        only when prediction is supported, and only when no *successful*
        prediction already exists.  It goes through the same validated
        execution and tracing path as every other tool call and respects the
        configured tool-call limit.

        Returns
        -------
        bool
            ``True`` when prediction is supported and missing but the
            tool-call limit prevented the fallback from running.
        """

        if "predict_risk" not in available:
            return False
        if any(run.tool == "predict_risk" and run.ok for run in results):
            return False

        index = len(results) + 1
        if len(results) >= self.max_tool_calls:
            self._trace.record(
                "prediction_fallback_skipped",
                tool="predict_risk",
                reason="tool_call_limit",
                call_index=index,
                risk_model=model_identity(self.twin.model),
                llm_provider=getattr(self._llm, "provider", None),
                llm_model=getattr(self._llm, "model", None),
            )
            return True

        call = ToolCallRequest(
            id=f"fallback-predict_risk-{index}",
            name="predict_risk",
            arguments="{}",
        )
        self._trace.record(
            "prediction_fallback",
            tool="predict_risk",
            reason="no_successful_prediction_after_llm_loop",
            call_index=index,
            risk_model=model_identity(self.twin.model),
            llm_provider=getattr(self._llm, "provider", None),
            llm_model=getattr(self._llm, "model", None),
        )
        results.append(
            self._run_tool_call(call, index, available, origin="fallback")
        )
        return False

    # -- conversation --------------------------------------------------

    @staticmethod
    def _assistant_message(turn: AssistantTurn) -> dict[str, Any]:
        message: dict[str, Any] = {
            "role": "assistant",
            "content": turn.content or "",
        }
        if turn.tool_calls:
            message["tool_calls"] = [
                {
                    "id": call.id,
                    "type": "function",
                    "function": {
                        "name": call.name,
                        "arguments": call.arguments,
                    },
                }
                for call in turn.tool_calls
            ]
        return message

    @staticmethod
    def _tool_message(call: ToolCallRequest, run: _ToolRun) -> dict[str, Any]:
        if run.ok:
            payload = {"ok": True, "tool": run.tool, "result": run.result}
        else:
            payload = {
                "ok": False,
                "tool": run.tool,
                "error": {
                    "type": run.error_type,
                    "message": run.error_message,
                },
            }
        return {
            "role": "tool",
            "tool_call_id": call.id,
            "content": json.dumps(payload, allow_nan=False, ensure_ascii=False),
        }

    def _system_prompt(self, available: list[str]) -> str:
        """Append the concrete capability set to the fixed system prompt."""

        model = self.twin.model
        unavailable: list[str] = []
        if not getattr(model, "supports_prediction", True):
            unavailable.append("risk prediction")
        if not getattr(model, "supports_explanation", True):
            unavailable.append("feature attribution (explain_risk)")
        if not getattr(model, "supports_simulation", True):
            unavailable.append("intervention simulation (simulate_intervention)")

        lines = [
            SYSTEM_PROMPT.rstrip(),
            "",
            "Available tools: " + ", ".join(available) + ".",
            "Only these tools are exposed. Do not attempt unavailable tools.",
        ]
        if unavailable:
            lines.append(
                "Unavailable for this risk model: "
                + "; ".join(unavailable)
                + ". State that plainly if asked; do not call or invent them."
            )
        return "\n".join(lines)

    def _user_message(self, request: str, hour: int) -> str:
        return (
            f"Clinician request: {request}\n\n"
            f"Patient context: patient_id={self.twin.patient_id!r}, "
            f"scored ICU hour={hour} (1-based), history rows={self.twin.hours}, "
            f"risk model={model_identity(self.twin.model)!r}.\n"
            "The patient and hour are fixed. Use the tools to obtain any "
            "patient-specific values. Do not estimate a probability yourself."
        )

    # -- public runs ---------------------------------------------------

    def run(self, request: str, patient_id: str, hour: int) -> dict[str, Any]:
        """Run the LLM tool loop and return the structured response."""

        if not isinstance(request, str) or not request.strip():
            raise AgentContextError("request must be a non-empty string")
        self._validate_context(patient_id, hour)
        if self._llm is None:
            raise AgentError(
                "No LLM client was supplied. Use run_tools_only() for the "
                "deterministic tool demonstration, or inject a ChatClient."
            )

        available = self.available_tools
        tools = openai_tool_specs(available)
        messages: list[dict[str, Any]] = [
            {"role": "system", "content": self._system_prompt(available)},
            {"role": "user", "content": self._user_message(request, hour)},
        ]
        results: list[_ToolRun] = []
        limit_reached = False

        self._trace.record(
            "run_start",
            mode="llm_agent",
            hour=hour,
            history_rows=self.twin.hours,
            risk_model=model_identity(self.twin.model),
            llm_provider=getattr(self._llm, "provider", None),
            llm_model=getattr(self._llm, "model", None),
            max_tool_calls=self.max_tool_calls,
            available_tools=available,
        )

        llm_failure: LLMError | None = None
        try:
            while True:
                turn = self._llm.complete(messages, tools)
                if not turn.tool_calls:
                    break

                messages.append(self._assistant_message(turn))
                stop_after_turn = False

                for call in turn.tool_calls:
                    if len(results) >= self.max_tool_calls:
                        limit_reached = True
                        self._trace.record(
                            "tool_call_skipped",
                            call_index=len(results) + 1,
                            tool=call.name,
                            tool_call_id=call.id,
                            reason="tool_call_limit",
                            risk_model=model_identity(self.twin.model),
                            llm_provider=getattr(self._llm, "provider", None),
                            llm_model=getattr(self._llm, "model", None),
                        )
                        stop_after_turn = True
                        continue

                    run = self._run_tool_call(
                        call,
                        len(results) + 1,
                        available,
                    )
                    results.append(run)
                    messages.append(self._tool_message(call, run))

                    if len(results) >= self.max_tool_calls:
                        limit_reached = True
                        stop_after_turn = True

                if stop_after_turn:
                    break
        except LLMError as exc:
            # A provider failure is terminal for the LLM loop: never retry it.
            # If tools already produced usable results, keep them and build a
            # deterministic summary below instead of discarding real work.
            successful = [run for run in results if run.ok]
            if not successful:
                self._trace.record(
                    "run_end",
                    status="error",
                    mode="llm_agent",
                    error_type=type(exc).__name__,
                    tool_calls=len(results),
                    retry_after_s=getattr(exc, "retry_after_s", None),
                )
                raise
            llm_failure = exc
            self._trace.record(
                "llm_failure",
                mode="llm_agent",
                error_type=type(exc).__name__,
                retry_after_s=getattr(exc, "retry_after_s", None),
                completed_tool_calls=len(successful),
                failed_tool_calls=sum(1 for run in results if not run.ok),
                summary_source="deterministic_fallback",
            )
        except Exception as exc:
            self._trace.record(
                "run_end",
                status="error",
                mode="llm_agent",
                error_type=type(exc).__name__,
                tool_calls=len(results),
            )
            raise

        prediction_fallback_skipped = self._ensure_prediction(results, available)

        response = _build_response(
            self.twin,
            hour,
            results,
            mode="llm_agent",
            limit_reached=limit_reached,
            max_tool_calls=self.max_tool_calls,
            prediction_fallback_skipped=prediction_fallback_skipped,
            summary_source=(
                "deterministic_fallback" if llm_failure is not None else "llm_agent"
            ),
            fallback_reason=(
                _llm_failure_note(llm_failure)
                if llm_failure is not None
                else None
            ),
        )
        _validate_response(response)

        self._trace.record(
            "run_end",
            status=(
                "llm_error_fallback"
                if llm_failure is not None
                else "limit_reached"
                if limit_reached
                else "completed"
                if results
                else "no_tool_calls"
            ),
            mode="llm_agent",
            tool_calls=len(results),
            failed_tool_calls=sum(1 for run in results if not run.ok),
            error_type=(
                type(llm_failure).__name__ if llm_failure is not None else None
            ),
            retry_after_s=(
                getattr(llm_failure, "retry_after_s", None)
                if llm_failure is not None
                else None
            ),
            summary_source=response["summary_source"],
        )
        return response

    def run_tools_only(self, patient_id: str, hour: int) -> dict[str, Any]:
        """Run a fixed, deterministic tool sequence without an LLM.

        This exists so the CLI can demonstrate the real patient loader, real
        risk model and response builder when no LLM credentials are available.
        It is labelled ``tools_only`` and is not presented as an agent run.
        """

        self._validate_context(patient_id, hour)
        available = self.available_tools

        plan: list[tuple[str, str]] = [
            ("get_twin_state", "{}"),
            ("predict_risk", "{}"),
            ("explain_risk", json.dumps({"top_k": 5})),
            ("risk_trajectory", json.dumps({"max_hours": 24})),
            ("clinical_scores", "{}"),
            ("list_interventions", "{}"),
            ("simulate_intervention", json.dumps({"intervention": "fluid_bolus"})),
            ("simulate_intervention", json.dumps({"intervention": "no_action"})),
        ]

        self._trace.record(
            "run_start",
            mode="tools_only",
            hour=hour,
            history_rows=self.twin.hours,
            risk_model=model_identity(self.twin.model),
            llm_provider=None,
            llm_model=None,
            max_tool_calls=self.max_tool_calls,
            available_tools=available,
        )

        results: list[_ToolRun] = []
        limit_reached = False
        try:
            for index, (name, arguments) in enumerate(plan, start=1):
                if index > self.max_tool_calls:
                    limit_reached = True
                    break
                call = ToolCallRequest(
                    id=f"tools-only-{index}",
                    name=name,
                    arguments=arguments,
                )
                if name not in available:
                    run = _ToolRun(
                        index=index,
                        tool=name,
                        ok=False,
                        error_type="tool_unavailable",
                        error_message=(
                            f"{name!r} is not supported by risk model "
                            f"{self.twin.model.name!r}"
                        ),
                        origin="tools_only",
                    )
                    self._trace_tool(run, call)
                else:
                    run = self._run_tool_call(
                        call, index, available, origin="tools_only"
                    )
                results.append(run)
        except Exception as exc:
            self._trace.record(
                "run_end",
                status="error",
                mode="tools_only",
                error_type=type(exc).__name__,
                tool_calls=len(results),
            )
            raise

        response = _build_response(
            self.twin,
            hour,
            results,
            mode="tools_only",
            limit_reached=limit_reached,
            max_tool_calls=self.max_tool_calls,
            summary_source="tools_only",
        )
        _validate_response(response)

        self._trace.record(
            "run_end",
            status="completed",
            mode="tools_only",
            tool_calls=len(results),
            failed_tool_calls=sum(1 for run in results if not run.ok),
        )
        return response


