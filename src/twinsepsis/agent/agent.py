def openai_tool_specs(names: Sequence[str]) -> list[dict[str, Any]]:
    """Convert our tool specs to the OpenAI ``tools`` wire format."""

    specs: list[dict[str, Any]] = []
    for name in names:
        spec = TOOL_SPECS[name]
        specs.append(
            {
                "type": "function",
                "function": {
                    "name": name,
                    "description": spec["description"],
                    "parameters": spec["parameters"],
                },
            }
        )
    return specs


