"""Tool-calling LLM agent for TwinSepsis.

The agent is intentionally conservative:

* the patient and scored hour are fixed *before* the LLM is called;
* only tools supported by the configured :class:`RiskModel` are exposed;
* every tool argument is validated against a JSON Schema;
* at most :data:`MAX_TOOL_CALLS` tool calls are executed per run;
* the final structured response is assembled from actual tool outputs, not
  from free-text generated by the model.

The model may choose tools and explain what it found, but it never supplies a
sepsis probability, a clinical measurement, a feature attribution or an
intervention effect.  Those values come only from the tool layer.
"""

