def _compact_scenario(simulation: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "intervention": simulation.get("intervention"),
        "label": simulation.get("label"),
        "available": simulation.get("available"),
        "effect_status": simulation.get("effect_status"),
        "reason": simulation.get("reason"),
        "source": simulation.get("source"),
        "source_kind": simulation.get("source_kind"),
        "projected_risk": simulation.get("projected_risk"),
        "bounds": simulation.get("bounds"),
        "bound_type": simulation.get("bound_type"),
        "baseline_no_action": simulation.get("baseline_no_action"),
        "unresolved": simulation.get("unresolved", []),
    }


def _scenario_status(item: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "intervention": item.get("name"),
        "label": item.get("label"),
        "available": item.get("available"),
        "effect_status": item.get("effect_status"),
        "reason": None
        if item.get("available")
        else "Unresolved assumptions: " + ", ".join(item.get("unresolved", [])),
        "projected_risk": None,
        "bounds": None,
        "unresolved": item.get("unresolved", []),
    }


def _add_unique(items: list[str], value: str) -> None:
    if value and value not in items:
        items.append(value)


def _llm_failure_note(exc: LLMError) -> str:
    """A short, provider-body-free description for fallback responses."""

    if getattr(exc, "status_code", None) == 429:
        note = "provider rate limit reached (HTTP 429)"
    else:
        note = type(exc).__name__
    retry_after = getattr(exc, "retry_after_s", None)
    if isinstance(retry_after, (int, float)):
        note += f"; retry after {retry_after:g} s"
    return note


def _build_response(
    twin: PatientTwin,
    hour: int,
    results: Sequence[_ToolRun],
    *,
    mode: str,
    limit_reached: bool,
    max_tool_calls: int,
    prediction_fallback_skipped: bool = False,
    summary_source: str = "llm_agent",
    fallback_reason: str | None = None,
) -> dict[str, Any]:
    model = twin.model
    prediction = _last_ok(results, "predict_risk")
    prediction_origin = next(
        (
            run.origin
            for run in reversed(results)
            if run.tool == "predict_risk" and run.ok
        ),
        None,
    )
    state = _last_ok(results, "get_twin_state")
    explanation = _last_ok(results, "explain_risk")
    trajectory = _last_ok(results, "risk_trajectory")
    interventions = _last_ok(results, "list_interventions")
    scores = _last_ok(results, "clinical_scores")

    simulations: dict[str, Mapping[str, Any]] = {}
    for run in results:
        if run.tool == "simulate_intervention" and run.ok:
            intervention = run.result.get("intervention")
            if isinstance(intervention, str):
                simulations[intervention] = run.result

    caveats: list[str] = []
    limitations: list[str] = []

    _add_unique(caveats, DISCLAIMER)
    _add_unique(
        caveats,
        f"Risk model {model.name!r} is trained on {model.dataset}; "
        "no MIMIC-IV model is available in this repository.",
    )
    if getattr(model, "test_only", False):
        _add_unique(
            caveats,
            "TEST-ONLY model: every number in this response is a synthetic "
            "fixture and must not be reported as a clinical or research result.",
        )
    if not getattr(model, "supports_prediction", True):
        _add_unique(
            caveats,
            "The configured model cannot produce a probability, so prediction "
            "tools were not exposed.",
        )
    if not getattr(model, "supports_explanation", True):
        _add_unique(caveats, "Feature attribution is unavailable for this model.")
        _add_unique(limitations, "feature_attribution_unavailable")
    if not getattr(model, "supports_simulation", True):
        _add_unique(
            caveats,
            "Intervention simulation is unavailable for this model, so "
            "simulation tools were not exposed.",
        )
        _add_unique(limitations, "intervention_simulation_unavailable")

    risk_summary: str | None = None
    prediction_source: dict[str, Any] | None = None
    prediction_horizon: dict[str, Any] | None = None
    top_drivers: list[Any] | None = None
    trajectory_points: list[Any] | None = None
    scenarios: list[dict[str, Any]] | None = None

    if prediction is not None:
        risk = float(prediction["risk"])
        threshold = float(prediction["threshold"])
        relation = "at or above" if risk >= threshold else "below"
        risk_summary = (
            f"Model-estimated risk at ICU hour {hour} is {risk:.3f}, {relation} "
            f"the frozen threshold of {threshold:.3f}."
        )

        if state is not None:
            trend = state.get("trend") or {}
            direction = trend.get("direction")
            if direction in {"rising", "falling", "stable"}:
                window = trend.get("window_hours")
                delta = trend.get("delta")
                if isinstance(window, int) and isinstance(delta, (int, float)):
                    risk_summary += (
                        f" Risk is {direction} over the last {window} h "
                        f"(delta {delta:+.3f})."
                    )

        prediction_source = {
            "model": prediction.get("risk_model"),
            "dataset": model.dataset,
            "artifact": getattr(model, "artifact", None),
            "threshold": prediction.get("threshold"),
            "explanation_units": getattr(model, "explanation_units", None),
        }
        prediction_horizon = {
            "type": "point",
            "scored_icu_hour": hour,
            "history_index": prediction.get("hour"),
            "description": getattr(
                model,
                "prediction_horizon",
                "Scored hour only; no multi-hour forecast.",
            ),
        }
    else:
        prediction_attempted = any(
            run.tool in {"predict_risk", "get_twin_state"} for run in results
        )
        if not getattr(model, "supports_prediction", True):
            _add_unique(
                caveats,
                "No risk value was produced because the configured model does "
                "not support prediction.",
            )
        elif prediction_fallback_skipped:
            _add_unique(
                caveats,
                "No risk value was produced: the tool-call limit was reached "
                "before the deterministic prediction fallback could run.",
            )
            _add_unique(
                limitations, "prediction_fallback_blocked_by_tool_limit"
            )
        elif prediction_attempted:
            _add_unique(
                caveats,
                "No risk value was produced: the prediction tool failed or was "
                "unavailable. No substitute value was inserted.",
            )
        else:
            _add_unique(
                caveats,
                "No risk value was produced because the assistant did not call "
                "the prediction tool.",
            )
        _add_unique(limitations, "risk_prediction_unavailable")

    if summary_source == "deterministic_fallback":
        label = "Deterministic system-generated summary (not an LLM response)."
        if risk_summary is None:
            risk_summary = (
                label
                + " No risk value was available from the completed tool calls."
            )
        else:
            risk_summary = f"{label} {risk_summary}"

    if explanation is not None:
        top_drivers = list(explanation.get("explanations") or [])
    elif prediction is not None:
        _add_unique(caveats, "No feature-attribution result is available.")

    if trajectory is not None:
        trajectory_points = list(trajectory.get("risks") or [])
    else:
        _add_unique(limitations, "risk_trajectory_not_requested")

    if simulations:
        scenarios = [
            _compact_scenario(simulation) for simulation in simulations.values()
        ]
    elif interventions is not None:
        scenarios = [
            _scenario_status(item) for item in interventions.get("interventions", [])
        ]

    if simulations:
        unavailable = [
            name
            for name, simulation in simulations.items()
            if not simulation.get("available")
        ]
        if unavailable:
            _add_unique(
                caveats,
                "No intervention effect was invented for "
                + ", ".join(sorted(unavailable))
                + "; their assumptions are unresolved and projected risk is null.",
            )
            _add_unique(limitations, "intervention_effects_unresolved")
    elif interventions is not None and not interventions.get("any_available"):
        _add_unique(
            caveats,
            "Intervention scenarios are unavailable because their effect "
            "assumptions and citations are still TODO.",
        )
        _add_unique(limitations, "intervention_effects_unresolved")

    if scores is not None:
        for key, label in (("qsofa", "qSOFA"), ("sirs", "SIRS")):
            score = scores.get(key) or {}
            if score and not score.get("complete"):
                available = score.get("available_count")
                total = score.get("max_score")
                missing = [
                    criterion.get("name")
                    for criterion in score.get("criteria", [])
                    if not criterion.get("available")
                ]
                detail = ", ".join(str(name) for name in missing if name)
                _add_unique(
                    caveats,
                    f"{label} is incomplete ({available}/{total} criteria "
                    f"available{': ' + detail if detail else ''}); missing "
                    "criteria were not treated as normal.",
                )
                _add_unique(limitations, f"{key}_incomplete")
        _add_unique(
            caveats,
            "qSOFA and SIRS are rule-based screening scores, not diagnoses.",
        )
    else:
        _add_unique(limitations, "clinical_scores_not_requested")

    for run in results:
        if run.ok:
            continue
        if run.error_type == "unknown_tool":
            _add_unique(
                caveats,
                f"Tool request {run.tool!r} was rejected because it is not a "
                "known tool.",
            )
        elif run.error_type == "tool_unavailable":
            _add_unique(
                caveats,
                f"Tool {run.tool!r} was not executed: {run.error_message}",
            )
        elif run.error_type == "invalid_arguments":
            _add_unique(
                caveats,
                f"Tool {run.tool!r} was rejected because its arguments were "
                f"invalid: {run.error_message}",
            )
        elif run.tool == "predict_risk" and prediction is not None:
            source = (
                "the deterministic fallback"
                if prediction_origin == "fallback"
                else "a later prediction call"
            )
            _add_unique(
                caveats,
                f"An earlier {run.tool!r} call failed ({run.error_type}); "
                f"{source} produced the risk value shown.",
            )
        else:
            _add_unique(
                caveats,
                f"Tool {run.tool!r} failed ({run.error_type}); no substitute "
                "value was produced.",
            )

    if limit_reached:
        _add_unique(
            caveats,
            f"The tool-call limit of {max_tool_calls} was reached; the response "
            "may be incomplete.",
        )
        _add_unique(limitations, "tool_call_limit_reached")

    if mode == "tools_only":
        _add_unique(
            caveats,
            "No LLM was used: this is a deterministic tool demonstration.",
        )

    if summary_source == "deterministic_fallback":
        reason = f" ({fallback_reason})" if fallback_reason else ""
        _add_unique(
            caveats,
            "The LLM planner failed"
            + reason
            + "; this is a deterministic, system-generated summary assembled "
            "from the completed tool results. It is not an LLM-generated "
            "response, and no missing value was filled in.",
        )
        _add_unique(limitations, "llm_summary_unavailable")

    if not results:
        _add_unique(
            caveats,
            "No tools were called, so no patient-specific results are available.",
        )

    _add_unique(limitations, "no_causal_treatment_effect_estimation")
    _add_unique(limitations, "no_mimic_iv_model")

    response: dict[str, Any] = {
        "patient_id": twin.patient_id,
        "hour": int(hour),
        "history_index": (prediction or {}).get("hour") if prediction else None,
        "risk_summary": risk_summary,
        "prediction_source": prediction_source,
        "prediction_horizon": prediction_horizon,
        "top_drivers": top_drivers,
        "trajectory": trajectory_points,
        "scenarios": scenarios,
        "clinical_scores": scores,
        "caveats": caveats,
        "limitations": limitations,
        "needs_clinician_review": True,
        "tools_used": [
            {
                "tool": run.tool,
                "ok": run.ok,
                "arguments": run.arguments,
                "error_type": run.error_type,
                "origin": run.origin,
            }
            for run in results
        ],
        "mode": mode,
        "summary_source": summary_source,
        "disclaimer": DISCLAIMER,
    }
    return _json_safe(response)


def _validate_response(response: Mapping[str, Any]) -> None:
    validator = jsonschema.Draft202012Validator(AGENT_RESPONSE_SCHEMA)
    errors = sorted(validator.iter_errors(response), key=lambda err: list(err.path))
    if errors:
        error = errors[0]
        path = "/".join(str(part) for part in error.absolute_path) or "<root>"
        raise AgentError(f"agent produced an invalid response at {path}: {error.message}")


